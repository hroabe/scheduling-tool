#!/usr/bin/env node
/**
 * Regenerates messages/<locale>/index.ts from messages/namespaces.json and
 * creates missing namespace files ({}), so every locale exposes the same shape.
 *
 *   node scripts/gen-messages-index.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'messages');
const locales = ['ja', 'en', 'zh', 'ko', 'es', 'fr', 'de', 'pt'];
const namespaces = JSON.parse(readFileSync(join(root, 'namespaces.json'), 'utf8'));

for (const locale of locales) {
    for (const ns of namespaces) {
        const file = join(root, locale, `${ns}.json`);
        if (!existsSync(file)) writeFileSync(file, '{}\n');
    }
    const body = [
        '// Generated by scripts/gen-messages-index.mjs - do not edit by hand',
        ...namespaces.map((ns) => `import ${ns} from './${ns}.json';`),
        '',
        'const messages = {',
        ...namespaces.map((ns) => `    ${ns},`),
        '};',
        '',
        'export default messages;',
        '',
    ].join('\n');
    writeFileSync(join(root, locale, 'index.ts'), body);
}
console.log(`Generated index for ${locales.length} locales x ${namespaces.length} namespaces`);
